const Database = require('better-sqlite3');
const path = require('path');
const fs = require('fs');

const DATA_DIR = process.env.DATA_DIR || path.join(__dirname, '..', '..', 'data');
if (!fs.existsSync(DATA_DIR)) fs.mkdirSync(DATA_DIR, { recursive: true });

const DB_PATH = process.env.DB_PATH || path.join(DATA_DIR, 'afriresq.db');
const db = new Database(DB_PATH);

db.pragma('journal_mode = WAL');
db.pragma('foreign_keys = ON');

const SCHEMA = `
CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT UNIQUE NOT NULL,
  email TEXT UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK(role IN ('citizen','responder','coordinator','admin')) DEFAULT 'citizen',
  preferred_language TEXT DEFAULT 'en',
  is_active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS organizations (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  type TEXT NOT NULL CHECK(type IN ('health_facility','police','fire','ngo','community_group','ambulance','other')),
  phone TEXT,
  lat REAL,
  lng REAL,
  address_text TEXT,
  verified INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- Responder profile: extends a user with skills, org affiliation, live location & availability
CREATE TABLE IF NOT EXISTS responder_profiles (
  user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  organization_id TEXT REFERENCES organizations(id),
  skills TEXT NOT NULL DEFAULT '[]',        -- JSON array e.g. ["medical","fire","first_aid","security"]
  verification_status TEXT NOT NULL DEFAULT 'pending' CHECK(verification_status IN ('pending','verified','rejected')),
  verification_notes TEXT,
  availability_status TEXT NOT NULL DEFAULT 'offline' CHECK(availability_status IN ('available','busy','offline')),
  current_lat REAL,
  current_lng REAL,
  last_location_at TEXT,
  rating_avg REAL NOT NULL DEFAULT 0,
  rating_count INTEGER NOT NULL DEFAULT 0,
  active_case_count INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS emergencies (
  id TEXT PRIMARY KEY,
  reporter_id TEXT REFERENCES users(id),
  reporter_phone TEXT,                      -- captured even for anonymous / USSD-style reports
  category TEXT NOT NULL CHECK(category IN ('medical','road_accident','fire','security','missing_person','disaster','other')),
  description TEXT,
  severity TEXT NOT NULL DEFAULT 'unclassified' CHECK(severity IN ('unclassified','low','moderate','high','critical')),
  priority_score REAL NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'reported' CHECK(status IN ('reported','classified','matching','matched','notified','accepted','in_progress','resolved','closed','cancelled')),
  lat REAL NOT NULL,
  lng REAL NOT NULL,
  address_text TEXT,
  location_accuracy_m REAL,
  channel TEXT NOT NULL DEFAULT 'app' CHECK(channel IN ('app','ussd','sms','web')),
  assigned_responder_id TEXT REFERENCES users(id),
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at TEXT NOT NULL DEFAULT (datetime('now')),
  resolved_at TEXT,
  first_notified_at TEXT,
  accepted_at TEXT
);

CREATE INDEX IF NOT EXISTS idx_emergencies_status ON emergencies(status);
CREATE INDEX IF NOT EXISTS idx_emergencies_lat_lng ON emergencies(lat, lng);
CREATE INDEX IF NOT EXISTS idx_responder_lat_lng ON responder_profiles(current_lat, current_lng);

-- Immutable audit trail: every state change / action on an emergency
CREATE TABLE IF NOT EXISTS emergency_events (
  id TEXT PRIMARY KEY,
  emergency_id TEXT NOT NULL REFERENCES emergencies(id) ON DELETE CASCADE,
  event_type TEXT NOT NULL,                 -- reported, classified, matched, notified, accepted, declined, status_changed, resolved, note
  actor_id TEXT REFERENCES users(id),
  details TEXT,                             -- JSON blob
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX IF NOT EXISTS idx_events_emergency ON emergency_events(emergency_id);

-- Candidate responder recommendations generated by the matching engine
CREATE TABLE IF NOT EXISTS matches (
  id TEXT PRIMARY KEY,
  emergency_id TEXT NOT NULL REFERENCES emergencies(id) ON DELETE CASCADE,
  responder_id TEXT NOT NULL REFERENCES users(id),
  distance_km REAL,
  skill_score REAL,
  total_score REAL,
  rank INTEGER,
  status TEXT NOT NULL DEFAULT 'proposed' CHECK(status IN ('proposed','notified','accepted','declined','expired')),
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  responded_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_matches_emergency ON matches(emergency_id);
CREATE INDEX IF NOT EXISTS idx_matches_responder ON matches(responder_id);

CREATE TABLE IF NOT EXISTS notifications (
  id TEXT PRIMARY KEY,
  user_id TEXT REFERENCES users(id),
  emergency_id TEXT REFERENCES emergencies(id),
  channel TEXT NOT NULL CHECK(channel IN ('push','sms','ussd','in_app','email')),
  message TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'queued' CHECK(status IN ('queued','sent','delivered','failed')),
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- token column stores a SHA-256 hash of the refresh token, never the raw
-- value, so a leaked database dump cannot be used to mint sessions.
CREATE TABLE IF NOT EXISTS refresh_tokens (
  token TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user ON refresh_tokens(user_id);

-- Web Push (VAPID) subscriptions, one row per browser/device a user has
-- opted into push notifications on. See services/providers/push.js.
CREATE TABLE IF NOT EXISTS push_subscriptions (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  endpoint TEXT NOT NULL UNIQUE,
  p256dh TEXT NOT NULL,
  auth TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX IF NOT EXISTS idx_push_subscriptions_user ON push_subscriptions(user_id);

-- Voice-note (and future photo/etc) attachments on a report. Stored as a
-- BLOB in SQLite rather than on disk so a single file/backup covers both —
-- the pilot's ephemeral hosting disk already makes on-disk files unreliable.
CREATE TABLE IF NOT EXISTS emergency_attachments (
  id TEXT PRIMARY KEY,
  emergency_id TEXT NOT NULL REFERENCES emergencies(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK(kind IN ('voice_note')),
  mime_type TEXT NOT NULL,
  data BLOB NOT NULL,
  duration_seconds REAL,
  uploaded_by TEXT REFERENCES users(id),
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX IF NOT EXISTS idx_attachments_emergency ON emergency_attachments(emergency_id);

-- One rating per resolved emergency, given by the reporter. Feeds
-- responder_profiles.rating_avg / rating_count.
CREATE TABLE IF NOT EXISTS emergency_ratings (
  id TEXT PRIMARY KEY,
  emergency_id TEXT NOT NULL UNIQUE REFERENCES emergencies(id) ON DELETE CASCADE,
  responder_id TEXT NOT NULL REFERENCES users(id),
  reporter_id TEXT NOT NULL REFERENCES users(id),
  stars INTEGER NOT NULL CHECK(stars BETWEEN 1 AND 5),
  comment TEXT,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);
`;

db.exec(SCHEMA);

module.exports = db;
